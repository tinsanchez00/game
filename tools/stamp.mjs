// Cache busting without a build step. Writes, between the stamp markers in
// index.html, an import map that adds a content hash to every module's URL
// (?v=<hash>), plus the stylesheet and entry script with their hashes. A
// browser then fetches a file again only when its content has changed.
//
// Usage: node tools/stamp.mjs        (rewrites index.html)
//        stampBlock(root)            (the expected block, for tests)

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const START = '<!-- stamp:start (generated by tools/stamp.mjs; do not edit) -->';
const END = '<!-- stamp:end -->';

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function hash(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 10);
}

const url = (root, file) => `./${relative(root, file).split(sep).join('/')}`;

/** The generated block for the files under `root` right now. */
export function stampBlock(root) {
  const modules = [...walk(join(root, 'src')), ...walk(join(root, 'vendor'))].filter((f) => f.endsWith('.js'));
  const imports = Object.fromEntries(modules.map((f) => [url(root, f), `${url(root, f)}?v=${hash(f)}`]));
  const css = join(root, 'src', 'ui', 'style.css');
  const main = join(root, 'src', 'main.js');
  const map = JSON.stringify({ imports }, null, 2).split('\n').map((l) => `  ${l}`).join('\n');
  return [
    START,
    '  <script type="importmap">',
    map,
    '  </script>',
    `  <link rel="stylesheet" href="src/ui/style.css?v=${hash(css)}">`,
    `  <script type="module" src="src/main.js?v=${hash(main)}"></script>`,
    `  ${END}`,
  ].join('\n');
}

/** The block currently in index.html, or null. */
export function currentBlock(html) {
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  return a < 0 || b < 0 ? null : html.slice(a, b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
  const file = join(root, 'index.html');
  const html = readFileSync(file, 'utf8');
  const old = currentBlock(html);
  if (!old) throw new Error('index.html has no stamp markers');
  writeFileSync(file, html.replace(old, stampBlock(root)));
  console.log('index.html stamped');
}
